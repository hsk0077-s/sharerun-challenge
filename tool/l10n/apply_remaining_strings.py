#!/usr/bin/env python3
"""Turn a filled remaining-ko-strings.json into lib/l10n/remaining_surface.dart.

Translators fill en, ja, zh-TW, es, pt-BR, de, fr, vi, th, id.
ko stays the source. This script does not edit widgets.

  python3 tool/l10n/apply_remaining_strings.py
  python3 tool/l10n/apply_remaining_strings.py --check
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_IN = ROOT / "docs" / "l10n" / "remaining-ko-strings.json"
DEFAULT_OUT = ROOT / "lib" / "l10n" / "remaining_surface.dart"

# JSON column -> app languageCode (MaterialApp locales).
APP_LANGUAGE = {
    "en": "en",
    "ja": "ja",
    "zh-TW": "zh",
    "es": "es",
    "pt-BR": "pt",
    "de": "de",
    "fr": "fr",
    "vi": "vi",
    "th": "th",
    "id": "id",
}


def dart_string(value: str) -> str:
    # Dollar signs must stay literal. Dart single quotes interpolate `$`.
    escaped = (
        value.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
        .replace("$", "\\$")
    )
    return "'" + escaped + "'"


def placeholder_tokens(item: dict) -> list[str]:
    return [row["format"] for row in item.get("placeholders") or [] if row.get("format")]


def validate(payload: dict) -> list[str]:
    errors = []
    strings = payload.get("strings")
    if not isinstance(strings, list) or not strings:
        return ["strings 배열이 비어 있습니다."]
    seen = set()
    for index, item in enumerate(strings):
        key = item.get("key") or f"#{index}"
        if key in seen:
            errors.append(f"{key}: 키가 겹칩니다.")
        seen.add(key)
        ko = item.get("ko") or ""
        if not ko.strip():
            errors.append(f"{key}: ko가 비어 있습니다.")
        for column in APP_LANGUAGE:
            text = item.get(column)
            if not isinstance(text, str) or not text.strip():
                errors.append(f"{key}: {column}가 비어 있습니다.")
                continue
            if text.strip() == ko.strip() and re.search(r"[\uac00-\ud7a3]", ko):
                errors.append(f"{key}: {column}가 한국어 원문과 같습니다.")
            for token in placeholder_tokens(item):
                if token not in text:
                    errors.append(f"{key}: {column}에 {token}가 없습니다.")
    return errors


def emit(payload: dict) -> str:
    by_lang: dict[str, list[tuple[str, str]]] = {code: [] for code in APP_LANGUAGE.values()}
    keys = []
    for item in payload["strings"]:
        key = item["key"]
        keys.append(key)
        for column, code in APP_LANGUAGE.items():
            by_lang[code].append((key, item[column]))
    lines = [
        "// Generated by tool/l10n/apply_remaining_strings.py.",
        "// Do not edit by hand. Fill docs/l10n/remaining-ko-strings.json and run the script again.",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// Screen strings that were still Korean. Lookup by the key in the JSON.",
        "class RemainingSurface {",
        "  const RemainingSurface._();",
        "",
        "  static const appLanguageOf = <String, String>{",
    ]
    for column, code in APP_LANGUAGE.items():
        lines.append(f"    {dart_string(column)}: {dart_string(code)},")
    lines += [
        "  };",
        "",
        "  static String text(Locale locale, String key) {",
        "    final table = _byLanguage[locale.languageCode] ?? _byLanguage['en'];",
        "    return table?[key] ?? key;",
        "  }",
        "",
        "  static const keys = <String>[",
    ]
    for key in keys:
        lines.append(f"    {dart_string(key)},")
    lines += ["  ];", ""]
    for code, rows in by_lang.items():
        lines.append(f"  static const _{code} = <String, String>{{")
        for key, value in rows:
            lines.append(f"    {dart_string(key)}: {dart_string(value)},")
        lines.append("  };")
        lines.append("")
    lines.append("  static const _byLanguage = <String, Map<String, String>>{")
    for code in by_lang:
        lines.append(f"    {dart_string(code)}: _{code},")
    lines += ["  };", "}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_IN)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="Validate only. Do not write Dart.")
    args = parser.parse_args()
    payload = json.loads(args.input.read_text(encoding="utf-8"))
    errors = validate(payload)
    if errors:
        print(f"{len(errors)} problems")
        for line in errors[:40]:
            print(line)
        if len(errors) > 40:
            print(f"... {len(errors) - 40} more")
        raise SystemExit(1)
    if args.check:
        print(f"ok {len(payload['strings'])} strings")
        return
    args.output.write_text(emit(payload), encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
